"""Read Outlook for Mac .olm archives."""

from __future__ import annotations

import logging
import re
import zipfile
from collections.abc import Iterator
from datetime import UTC, datetime
from pathlib import Path
from xml.etree import ElementTree

from core.mail.importer.message import ImportedMessage
from core.mail.importer.text import clean_header, clean_text, html_to_text, parse_sent_at

logger = logging.getLogger(__name__)


# A field holds markup when it contains a CLOSING tag. Derived from the corpus
# rather than picked: of 28,451 .olm bodies, 27,221 contain a "<" at all and
# 27,198 contain a closing tag, so the 23 that differ are plain text using "<"
# legitimately - a bare address in angle brackets, or "a < b". Matching on "<"
# alone would run those through a stripper that has nothing to strip.
_MARKUP = re.compile(r"</[a-z][a-z0-9]*>", re.IGNORECASE)


def _olm_body(body: str | None, html: str | None) -> tuple[str | None, str | None]:
    """Choose readable .olm text by content, not the export field name.

    In the measured archive, 27,221 of 28,451 body fields contained tags and
    20,359 contained CSS. Convert markup before storing body_text, while
    retaining the original markup separately."""
    if body and not _MARKUP.search(body):
        # Genuinely plain: there is no markup to keep.
        return body, None
    markup = html or body
    if not markup:
        return None, None
    return html_to_text(markup) or None, markup


def read_olm(path: Path | str, *, source: str = "olm") -> Iterator[ImportedMessage]:
    """Stream an Outlook for Mac archive.

    .olm is a ZIP whose message XML lives under Accounts/.../Message/. Each
    file holds one or more <email> elements. Entries are read one at a time so
    a 4.4 GB archive never lands in memory.
    """
    with zipfile.ZipFile(path) as zf:
        for info in zf.infolist():
            if info.is_dir() or not info.filename.lower().endswith(".xml"):
                continue
            try:
                with zf.open(info) as fh:
                    raw = fh.read()
            except Exception:
                logger.warning("olm: unreadable entry %s, skipping", info.filename)
                continue
            yield from _olm_entries(raw, source=source, origin=info.filename)


def _olm_text(node: ElementTree.Element, *names: str) -> str | None:
    for name in names:
        found = node.find(name)
        if found is not None and (found.text or "").strip():
            return (found.text or "").strip()
    return None


_DOCTYPE = re.compile(rb"<!DOCTYPE", re.IGNORECASE)


def _olm_parse(raw: bytes) -> ElementTree.Element | None:
    """Parse one .olm XML entry, refusing anything carrying a DOCTYPE.

    The archive is generated by Outlook from the owner's own mailbox, so it is
    not untrusted input in the usual sense - but message CONTENT inside it came
    from arbitrary senders, and ElementTree does expand internal entities
    (verified: `<!ENTITY a "boom">` resolves), so a billion-laughs bomb would
    hang a 38,685-message import with no error and nothing pointing at the
    cause.

    Entity expansion requires a DOCTYPE internal subset, and Outlook does not
    emit a DOCTYPE, so refusing them closes the whole class at the cost of
    nothing legitimate. This is deliberately a content check rather than a
    parser hook: ElementTree's XMLParser exposes no handler to install one on,
    and pulling in defusedxml for a single call site is not worth a dependency.
    """
    if _DOCTYPE.search(raw[:4096]):
        return None
    try:
        return ElementTree.fromstring(raw)  # noqa: S314 - DOCTYPE refused above
    except ElementTree.ParseError:
        return None


def _bracketed(message_id: str | None) -> str | None:
    """A Message-ID as the header spells it, inside angle brackets. Outlook's
    export drops them, so the same message imported from .olm and from
    Takeout stored twice under two ids: 227 pairs on 2026-10-10."""
    if not message_id or message_id.startswith("<"):
        return message_id
    return f"<{message_id}>"


def _olm_entries(raw: bytes, *, source: str, origin: str) -> Iterator[ImportedMessage]:
    root = _olm_parse(raw)
    if root is None:
        logger.warning("olm: unparsable xml in %s, skipping", origin)
        return
    for idx, node in enumerate(root.iter("email")):
        text, html_source = _olm_body(
            _olm_text(node, "OPFMessageCopyBody"),
            _olm_text(node, "OPFMessageCopyHTMLBody"),
        )
        addresses = [
            (e.get("OPFContactEmailAddressAddress") or "")
            for e in node.iter("emailAddress")
            if e.get("OPFContactEmailAddressAddress")
        ]
        sender, sender_name = _olm_sender(node)
        yield ImportedMessage(
            provider_message_id=(
                _bracketed(clean_header(_olm_text(node, "OPFMessageCopyMessageID")))
                or f"{source}-{origin}-{idx}"
            ),
            source=source,
            # No thread id: this export exposes no conversation identity. The
            # nearest thing it offers, ThreadTopic, is a normalised subject,
            # and putting it here made every ATS autoresponder sharing a
            # subject line look like one conversation.
            provider_thread_id=None,
            thread_topic=clean_header(_olm_text(node, "OPFMessageCopyThreadTopic")),
            from_email=clean_header(sender),
            from_name=clean_header(sender_name or _olm_text(node, "OPFMessageCopyFromAddresses")),
            to_emails=[r for r in (clean_header(a) for a in addresses) if r and r != sender],
            subject=clean_header(_olm_text(node, "OPFMessageCopySubject")),
            sent_at=_olm_sent_at(node),
            body_text=(clean_text(text) if text else None),
            body_html=html_source,
        )


def _olm_sender(node: ElementTree.Element) -> tuple[str | None, str | None]:
    """The sender's address and display name. Outlook writes both as
    attributes of an emailAddress element; the holder element has no text
    of its own, so reading its text stored no name for any .olm message
    (0 of 28,224 on 2026-10-31)."""
    holder = node.find("OPFMessageCopyFromAddresses")
    if holder is None:
        return None, None
    for addr in holder.iter("emailAddress"):
        value = addr.get("OPFContactEmailAddressAddress")
        if value:
            return value, addr.get("OPFContactEmailAddressName")
    return None, None


def _olm_sent_at(node: ElementTree.Element) -> datetime | None:
    raw = _olm_text(node, "OPFMessageCopySentTime", "OPFMessageCopyReceivedTime")
    if not raw:
        return None
    try:
        parsed = datetime.fromisoformat(raw.replace("Z", "+00:00"))
    except ValueError:
        return parse_sent_at(raw)
    return parsed.replace(tzinfo=UTC) if parsed.tzinfo is None else parsed.astimezone(UTC)
